import { parseWeight, fmtWeight } from '../weight.js';
let fail = 0; const eq = (a, b, m) => { const ok = JSON.stringify(a) === JSON.stringify(b); if (!ok) fail++; console.log(ok ? 'ok  ' : 'FAIL', m, ok ? '' : `got ${JSON.stringify(a)} want ${JSON.stringify(b)}`); };
eq(parseWeight('85'), { kg: 85 }, '85');
eq(parseWeight('85.5'), { kg: 85.5 }, '85.5');
eq(parseWeight('85,5'), { kg: 85.5 }, '85,5 (decimal comma)');
eq(parseWeight(' 85 kg '), { kg: 85 }, '85 kg');
eq(parseWeight('13st 4lb'), { kg: 84.4 }, '13st 4lb');
eq(parseWeight('13 stone 4 pounds'), { kg: 84.4 }, '13 stone 4 pounds');
eq(parseWeight('13st'), { kg: 82.6 }, '13st');
eq(parseWeight('13', 'st'), { kg: 82.6 }, '13 in stone mode');
eq(parseWeight('13 4', 'st'), { kg: 84.4 }, '"13 4" in stone mode');
eq(parseWeight('190lb'), { kg: 86.2 }, '190lb');
eq(parseWeight('190', 'lb'), { kg: 86.2 }, '190 in lb mode');
eq(parseWeight('186,5 lbs'), { kg: 84.6 }, '186,5 lbs');
eq(!!parseWeight('').error, true, 'empty -> error');
eq(!!parseWeight('abc').error, true, 'garbage -> error');
eq(!!parseWeight('8').error, true, 'too low -> error');
eq(!!parseWeight('850').error, true, 'too high -> error');
eq(fmtWeight(84.4, 'st'), '13st 4lb', 'format stone');
process.exitCode = fail ? 1 : 0; console.log(fail ? `${fail} failed` : 'all weight tests passed');
