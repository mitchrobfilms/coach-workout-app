// Preview screenshots for the fitness studio. Usage: node tests/fitness-shots.mjs [url] [outdir]
import { chromium } from 'playwright-core';
import fs from 'node:fs';
const URL = process.argv[2] || 'http://127.0.0.1:8765/?fitdemo=1';
const OUT = process.argv[3] || '/opt/cursor/artifacts';
fs.mkdirSync(OUT, { recursive: true });
let fail = 0; const ok = (c, m) => { console.log(`${c ? 'ok  ' : 'FAIL'} ${m}`); if (!c) fail++; };
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--disable-http2'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, serviceWorkers: 'block', permissions: ['notifications'] });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto(URL, { waitUntil: 'domcontentloaded' });
await p.evaluate(() => localStorage.clear());
await p.goto(URL, { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(400);
if (await p.isVisible('#wCreate')) {
  await p.click('#wCreate');
  await p.fill('#regName', 'Sample'); await p.fill('#regEmail', 'fitdemo@example.com'); await p.fill('#regSecret', 'password123');
  await p.click('#regBtn'); await p.waitForTimeout(800);
}
if (await p.isVisible('#obSkip')) await p.click('#obSkip');
await p.evaluate(() => { const k = Object.keys(localStorage).find(x => x.endsWith('.settings')); if (!k) return; const s = JSON.parse(localStorage[k] || '{}'); s.onboarded = true; localStorage[k] = JSON.stringify(s); });
await p.goto(URL, { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(500);
if (await p.locator('#authScreen:not([hidden])').count()) await p.evaluate(() => { document.querySelectorAll('.overlay').forEach(e => { e.hidden = true; }); });
await p.evaluate(() => window.__kova.switchTab('workouts'));
await p.waitForFunction(() => window.__kova?.fitness?.ready && window.__kova?.videosReady, null, { timeout: 15000 });
ok(await p.locator('#fitDemoBanner').isVisible(), 'sample banner is visible');
ok(/02:/.test(await p.locator('#fitCountdown').innerText()), 'home shows a countdown');
ok(await p.locator('#videoLib .vtile').count() >= 5, 'Coach Ava tiles stay on the fitness home');
ok(await p.locator('#fitCourse').isVisible(), 'course banner stays visible');
const shot = async name => {
  await p.evaluate(() => { const t = document.getElementById('toast'); if (t) t.hidden = true; scrollTo(0, 0); });
  if (name === 'fitness-filters') await p.evaluate(() => document.getElementById('fitFilters')?.scrollIntoView({ block: 'start' }));
  if (name === 'fitness-live-chat') await p.evaluate(() => { const h = document.querySelector('[data-fitview="room"] h2'); if (!h) return; const y = h.getBoundingClientRect().top + scrollY - 64; scrollTo(0, Math.max(0, y)); });
  await p.waitForTimeout(120);
  await p.screenshot({ path: `${OUT}/${name}.png` });
};
await shot('fitness-home');
await p.evaluate(() => window.__kova.fitness.show('live'));
await p.waitForTimeout(200);
ok(/Coming up|On now|Replays/.test(await p.locator('#fitHub').innerText()) && /\d\d:\d\d|Live now/.test(await p.locator('#fitHub').innerText()), 'timetable lists classes and a countdown');
await shot('fitness-timetable');
await p.evaluate(() => window.__kova.fitness.show('room', 'demo-live'));
await p.waitForTimeout(200);
ok(/Coming soon/.test(await p.locator('#fitSoon').innerText()), 'live video is coming soon');
ok(/Sample Member/.test(await p.locator('#fitChat').innerText()), 'sample chat is on the class');
await p.fill('#fxChatForm input', 'Small steps feel better today');
await p.click('#fxChatForm button');
await p.waitForTimeout(200);
ok(/Small steps feel better today/.test(await p.locator('#fitChat').innerText()), 'a normal message appears in class chat');
await p.fill('#fxChatForm input', 'you should take 2.5 mg');
await p.click('#fxChatForm button');
await p.waitForTimeout(300);
ok(/cannot include doses/.test(await p.locator('#toast').innerText()), 'a dose is refused in class chat');
ok(!/2\.5 mg/.test(await p.locator('#fitChat').innerText()), 'the dose is not shown in the chat');
await shot('fitness-live-chat');
await p.evaluate(() => window.__kova.fitness.openPreview('gentle-start-8'));
await p.waitForTimeout(200);
const before = await p.locator('[data-p="clock"]').innerText();
ok(/Sit to stand|March|Wall|Glute|reps/.test(await p.locator('#fitPlayer').innerText()) && before !== '0:00', 'player opens mid-session on a move: ' + before);
await p.click('#fitPlayer [data-px="pause"]');
await p.waitForTimeout(1200);
const after = await p.locator('[data-p="clock"]').innerText();
ok(after !== before, 'the timer moves after resume: ' + before + ' -> ' + after);
ok(/Stop if anything hurts/.test(await p.locator('#fitPlayer').innerText()) && /does not play music/.test(await p.locator('#fitPlayer').innerText()), 'safety note and music note are on the player');
await p.screenshot({ path: `${OUT}/fitness-player.png` });
await p.evaluate(() => window.__kova.fitness.closePlayer());
await p.evaluate(() => window.__kova.fitness.show('programme', 'start-up'));
await p.waitForTimeout(150);
ok(/Start-Up/.test(await p.locator('#fitHub').innerText()) && /Rest/.test(await p.locator('#fitHub').innerText()) && /Too hard/.test(await p.locator('#fitHub').innerText()), 'programme shows the week and feedback');
await shot('fitness-programme');
await p.evaluate(() => window.__kova.fitness.show('plan'));
await p.waitForTimeout(150);
ok(/Monday/.test(await p.locator('#fitHub').innerText()) && /Rest/.test(await p.locator('#fitHub').innerText()), 'planner shows the week');
await shot('fitness-planner');
await p.evaluate(() => window.__kova.fitness.setFilters({ minMinutes: 10, maxMinutes: 20, level: 'beginner', focus: 'cardio', equipment: 'none', intensity: 'low' }));
await p.waitForTimeout(150);
ok(/10–20/.test(await p.locator('#fitFilters').innerText()) && /Steady march|Easy march/.test(await p.locator('#fitHub').innerText()), 'filters narrow the list');
await shot('fitness-filters');
await p.evaluate(() => window.__kova.fitness.show('trophies'));
await p.waitForTimeout(150);
ok(/week streak/.test(await p.locator('#fitHub').innerText()) && /kcal estimate/.test(await p.locator('#fitHub').innerText()) && /Sample/.test(await p.locator('#fitHub').innerText()), 'trophies show streaks, sample history and an estimate');
await shot('fitness-trophies');
await p.evaluate(() => window.__kova.fitness.show('health'));
await p.waitForTimeout(150);
ok(/Write workouts: Off/.test(await p.locator('#fitHealth').innerText()) && /Log a workout by hand/.test(await p.locator('#fitHub').innerText()) && /does not play music/.test(await p.locator('#fitHub').innerText()), 'Health Connect write is off, with manual entry and the music note');
await shot('fitness-health');
await p.evaluate(() => window.__kova.fitness.show('tip', 'protein'));
await p.waitForTimeout(150);
ok(/Protein when meals are smaller/.test(await p.locator('#fitHub').innerText()) && /GP/.test(await p.locator('#fitHub').innerText()), 'a tip is original and points to a GP');
await shot('fitness-tips');
ok(errs.length === 0, 'no page errors: ' + errs.join(' | '));
await b.close();
console.log(fail ? fail + ' SHOT CHECKS FAILED' : 'SHOTS OK');
process.exit(fail ? 1 : 0);
